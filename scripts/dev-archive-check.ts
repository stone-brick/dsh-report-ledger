// A module, not a global script: without an import/export this file shares the
// global scope with its siblings, so top-level names like `checks` collide
// across scripts and `filter` silently resolves to the DOM's window.filter.
// Emitted as nothing; it exists so `tsc` treats the file as its own module.
export {}
/**
 * Deterministic checks for the developer-mode archive.
 *
 * The archive is the part of the history that survives a fork, so the things
 * worth pinning are the ones that decide whether it is trustworthy:
 *
 *  - **It says what it left out.** A distillation that hides its omissions reads as
 *    complete, which is worse than no distillation.
 *  - **It is bounded.** The caps are what keep it from becoming a second, quieter
 *    context tax on every development turn.
 *  - **The index round-trips.** It is generated and later parsed back into the
 *    prompt block; a writer and a reader that disagree would silently inject
 *    nothing.
 *
 * Run: node scripts/dev-archive-check.ts
 */

const {
  MAX_ARCHIVE_BYTES,
  MAX_INDEX_LINES,
  parseIndex,
  renderArchive,
  renderIndex,
  renderIndexBlock,
  sectionsOf,
  topicSlug,
} = await import('../src/report/dev/archive.ts')

const checks: [string, boolean, string][] = []
const check = (label: string, ok: boolean, detail = ''): void => { checks.push([label, ok, detail]) }

const front = {
  report: 'R-0025',
  subject: 'views: 汇报视图审计',
  status: 'closed' as const,
  from: 'session-a',
  to: ['session-b'],
  cc: [],
  authors: ['session-a', 'session-b'],
  created: 1,
  updated: 1792494398324,
  children: [],
  task: 'views',
  artifacts: [],
  hops: 19,
  reads: 0,
}

// ---- slugs ---------------------------------------------------------------
check('a plain label becomes its own slug', topicSlug('views') === 'views')
check('a dashed label survives', topicSlug('release-eng') === 'release-eng')
check('spaces and slashes collapse to single dashes', topicSlug('a b/c') === 'a-b-c', topicSlug('a b/c'))
check('a label that slugs to nothing becomes the fallback', topicSlug('中文标签') === 'archive', topicSlug('中文标签'))
check('leading and trailing dashes are trimmed', topicSlug('--x--') === 'x', topicSlug('--x--'))
check('a very long slug is truncated', topicSlug('a'.repeat(200)).length === 60)

// ---- section splitting ---------------------------------------------------
const body = [
  '前言，没有标题。',
  '',
  '## 任务',
  '做审计。',
  '',
  '## 1. 结论',
  '结论是要点。',
  '',
  '### 结论',
  '子结论也要保留。',
  '',
  '## 5. 测试',
  '96 项通过。',
].join('\n')
const sections = sectionsOf(body)
check('the preamble is its own section', sections[0]?.heading === undefined, JSON.stringify(sections[0]))
check('every heading starts a section', sections.filter((section) => section.heading !== undefined).length === 4,
  String(sections.length))
check('a heading keeps its body', sections.some((section) => section.text.includes('96 项通过')))

// ---- the archive keeps conclusions and names omissions -------------------
const topic = { topic: 'views', file: 'views.md', summary: '视图审计结论', reports: ['R-0025'], updated: front.updated }
const archived = renderArchive(topic, [{ front, body }])
check('the archive names itself as generated', archived.includes('generated by dev_archive'))
check('the archive carries the topic metadata', archived.includes('- topic: views') && archived.includes('- summary: 视图审计结论'))
check('the archive carries the outline', archived.includes('## outline') && archived.includes('- 1. 结论'))
check('a conclusion section is kept in full', archived.includes('结论是要点。'))
check('a sub-conclusion is kept in full', archived.includes('子结论也要保留。'))
check('a non-conclusion section is omitted', !archived.includes('96 项通过'))
check('the omission is named', /omitted sections \(\d+\):[\s\S]*- 任务/.test(archived), archived.slice(0, 0))
check('the digest is present', archived.includes('- status: closed · task: views · hops: 19'))

// ---- the byte budget is real --------------------------------------------
const huge = Array.from({ length: 4000 }, (_, index) => `## 结论 ${index}\n${'长文本'.repeat(40)}`).join('\n')
const capped = renderArchive(topic, [{ front, body: huge }])
check('the archive respects its byte budget',
  Buffer.byteLength(capped, 'utf8') <= MAX_ARCHIVE_BYTES + 200, String(Buffer.byteLength(capped, 'utf8')))
check('truncation is announced, not silent', capped.includes('truncated at the'))

// ---- index round-trip ----------------------------------------------------
const indexText = renderIndex([topic, { ...topic, topic: 'canvas', file: 'canvas.md', summary: '带 "引号" 与中文' }], Date.now())
const parsed = parseIndex(indexText)
check('the index round-trips both topics', parsed.topics.length === 2, String(parsed.topics.length))
check('a quoted summary survives the round-trip',
  parsed.topics.some((entry) => entry.summary === '带 "引号" 与中文'), JSON.stringify(parsed.topics.map((entry) => entry.summary)))
check('the timestamp survives the round-trip',
  parsed.topics.find((entry) => entry.topic === 'views')?.updated === front.updated)
check('a broken index parses to an empty archive', parseIndex('topics: [\n').topics.length === 0)
check('a non-object index parses to an empty archive', parseIndex('- just\n- a list\n').topics.length === 0)

// ---- the injected block --------------------------------------------------
check('no archive means no block', renderIndexBlock([]) === '')
const block = renderIndexBlock([topic])
check('the block names the topic and the file', block.includes('views') && block.includes('dev/archive/views.md'))
check('the block says the details are on demand', block.includes('按需读文件'))
const many = Array.from({ length: MAX_INDEX_LINES + 5 }, (_, index) => ({
  ...topic,
  topic: `t${String(index).padStart(3, '0')}`,
  file: `t${String(index).padStart(3, '0')}.md`,
}))
const cappedBlock = renderIndexBlock(many)
const listed = cappedBlock.split('\n').filter((line) => line.startsWith('- t')).length
check('the block caps the listed topics', listed === MAX_INDEX_LINES, String(listed))
check('the overflow is named', cappedBlock.includes('另有 5 条'))

let failed = 0
for (const [label, ok, detail] of checks) {
  if (!ok) failed++
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${label}${ok || detail === '' ? '' : `  <- ${detail}`}`)
}
console.log('')
console.log(`${checks.length - failed}/${checks.length} checks passed`)
process.exit(failed === 0 ? 0 : 1)
